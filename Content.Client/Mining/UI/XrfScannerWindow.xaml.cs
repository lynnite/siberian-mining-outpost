using System.Numerics;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.Mining;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Mining.UI;

[GenerateTypedNameReferences]
public sealed partial class XrfScannerWindow : FancyWindow
{
    [Dependency] private IResourceCache _cache = default!;

    public XrfScannerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Populate(XrfScannerBoundUserInterfaceState state)
    {
        var hasData = state.RockEntries.Count > 0 || state.OreEntries.Count > 0;
        NoDataLabel.Visible = !hasData;
        ContentContainer.Visible = hasData;

        if (!hasData)
            return;

        RockContainer.RemoveAllChildren();
        foreach (var entry in state.RockEntries)
            RockContainer.AddChild(CreateEntryRow(entry));

        OreContainer.RemoveAllChildren();
        if (state.OreEntries.Count == 0)
        {
            OreSeparator.Visible = false;
            OreHeader.Visible = false;
        }
        else
        {
            OreSeparator.Visible = true;
            OreHeader.Visible = true;
            foreach (var entry in state.OreEntries)
                OreContainer.AddChild(CreateEntryRow(entry));
        }
    }

    private BoxContainer CreateEntryRow(XrfEntry entry)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 2, 0, 2),
        };

        var texture = ResolveTexture(entry);
        if (texture != null)
        {
            row.AddChild(new TextureRect
            {
                Texture = texture,
                SetSize = new Vector2(32, 32),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                Margin = new Thickness(0, 0, 6, 0),
            });
        }

        var text = new RichTextLabel { HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        text.SetMarkup(Loc.GetString("xrf-scanner-window-entry",
            ("name", entry.Name),
            ("percent", $"{entry.Percentage:0.##}")));
        row.AddChild(text);

        return row;
    }

    private Texture? ResolveTexture(XrfEntry entry)
    {
        if (string.IsNullOrEmpty(entry.SpriteState))
            return null;

        var path = string.IsNullOrEmpty(entry.SpritePath)
            ? new ResPath("/Textures/Objects/Materials/ore.rsi")
            : ResolveRsiPath(entry.SpritePath);

        if (!_cache.TryGetResource<RSIResource>(path, out var rsiRes))
            return null;

        if (!rsiRes.RSI.TryGetState(entry.SpriteState, out var rsiState))
            return null;

        return rsiState.Frame0;
    }

    private static ResPath ResolveRsiPath(string spritePath)
    {
        var path = new ResPath(spritePath);
        if (path.IsRooted)
            return path;

        return new ResPath("/Textures") / path;
    }
}
